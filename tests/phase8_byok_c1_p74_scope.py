class OfflineC1AdmissionRefused(AssertionError):
    """Admission denial with nonsecret, bounded diagnostic only."""


def _fail(reason: str):
    raise OfflineC1AdmissionRefused("P74 offline scope refused: " + reason)


def _git(*args):
    # Authenticated Git executable, clean environment and no network/fetch
    # are inherited from the sealed prior read-only Git helper.
    return sealed._git(*args)


def _disk(path: str) -> bytes:
    return sealed._disk(path)


def _oid(*args):
    raw = _git(*args)
    if type(raw) is not bytes or re.fullmatch(rb"[0-9a-f]{40}\n", raw) is None:
        _fail("invalid Git object identifier")
    return raw[:-1].decode("ascii")


def _digest(path, raw):
    if type(raw) is not bytes:
        _fail("non-byte source")
    if path == SELF:
        hits = tuple(_SELF_PIN.finditer(raw))
        if len(hits) != 1:
            _fail("invalid candidate self-pin syntax")
        raw, changed = _SELF_PIN.subn(
            lambda m: m[1] + b"0" * 64 + m[2], raw
        )
        if changed != 1:
            _fail("invalid candidate self-pin count")
    return hashlib.sha256(raw).hexdigest().upper()


def _tag():
    ref = _oid("show-ref", "--verify", "--hash", "--", "refs/tags/" + PARENT_TAG)
    if ref != PARENT_TAG_OBJECT:
        _fail("sealed Phase10.3 tag reference changed")
    if _git("cat-file", "-t", ref) != b"tag\n":
        _fail("sealed tag is not annotated")
    raw = _git("cat-file", "tag", ref)
    if (sealed.prior._object("tag", raw) != ref
            or raw.split(b"\n")[:3] != [
                ("object " + PARENT).encode("ascii"),
                b"type commit",
                ("tag " + PARENT_TAG).encode("ascii"),
            ]
            or _oid("rev-parse", "--verify", "--end-of-options", ref + "^{}")
            != PARENT):
        _fail("sealed Phase10.3 raw tag mismatch")


def _baseline():
    _tag()
    if (_git("rev-parse", "--show-object-format") != b"sha1\n"
            or sealed._commit(PARENT) != (PARENT_TREE, [PARENT_PARENT])
            or _oid("rev-parse", PARENT + "^{tree}") != PARENT_TREE):
        _fail("sealed Phase10.3 parent commit/tree mismatch")
    baseline = sealed._tree(PARENT)
    if len(baseline) != PARENT_COUNT:
        _fail("sealed Phase10.3 inventory count mismatch")
    return baseline


def _expected(baseline):
    if (len(ENVELOPE) != 8 or set(CANDIDATE_SHA256) != ENVELOPE
            or SELF not in ENVELOPE or TEST not in ENVELOPE
            or any(path in baseline for path in ENVELOPE)):
        _fail("wrong additive manifest")
    expected = dict(baseline)
    for path, pin in CANDIDATE_SHA256.items():
        if (type(pin) is not str or re.fullmatch(r"[A-F0-9]{64}", pin) is None
                or pin == "0" * 64):
            _fail("missing reviewed source pin")
        raw = _disk(path)
        if path == SELF:
            match = tuple(_SELF_PIN.finditer(raw))
            if len(match) != 1 or match[0][0].find(pin.encode("ascii")) == -1:
                _fail("self pin literal does not match")
        if _digest(path, raw) != pin:
            _fail("candidate byte mismatch: " + path)
        expected[path] = ("100644", sealed.prior._blob(raw))
    # No old source is approved for modification, regardless of Git metadata.
    for path, (mode, oid) in baseline.items():
        raw = _disk(path)
        if sealed.prior._blob(raw) != oid:
            _fail("sealed historical source changed: " + path)
    return expected


def _proof(head, baseline, expected, committed, index, untracked):
    cached = _git(*RAW, "--cached")
    working = _git(*RAW)
    if head == PARENT:
        if committed != baseline:
            _fail("parent tree changed")
        if index == baseline:
            if untracked != ENVELOPE:
                _fail("missing or extra untracked source")
            sealed._delta(cached, baseline, index, set())
            sealed._delta(working, index, expected, set(), work=True)
            return "COMPLETE_UNSTAGED"
        if index != expected or untracked:
            _fail("partial stage or unapproved source")
        sealed._delta(cached, baseline, expected, ENVELOPE)
        sealed._delta(working, index, expected, set(), work=True)
        return "EXACT_STAGED"
    _, parents = sealed._commit(head)
    if (parents != [PARENT] or
            _git("rev-list", "--parents", "-n", "1", head) !=
            (head + " " + PARENT + "\n").encode("ascii")):
        _fail("requires immediate Phase10.3 child")
    if committed != expected or index != expected or untracked:
        _fail("unapproved committed inventory or workspace")
    sealed._delta(cached, committed, index, set())
    sealed._delta(working, index, expected, set(), work=True)
    sealed._delta(_git(*RAW, PARENT, head), baseline, expected, ENVELOPE)
    return "EXACT_CHILD"


def assert_p74_offline_integrity():
    """Fresh fail-closed read-only source proof; grants NO effect authority."""
    if _git("branch", "--show-current") != (BRANCH + "\n").encode("ascii"):
        _fail("wrong exact C1 offline branch")
    head = _oid("rev-parse", "HEAD")
    baseline = _baseline()
    expected = _expected(baseline)
    committed = sealed._tree(head)
    index, untracked = sealed._working_inventory(committed)
    result = _proof(head, baseline, expected, committed, index, untracked)
    # A second un-cached view detects source/index/ref drift within admission.
    if (_expected(baseline) != expected
            or sealed._tree(head) != committed
            or sealed._working_inventory(committed) != (index, untracked)
            or _proof(head, baseline, expected, committed, index, untracked)
            != result):
        _fail("source or Git view changed during admission")
    if (_oid("rev-parse", "HEAD") != head
            or _git("branch", "--show-current") !=
            (BRANCH + "\n").encode("ascii")):
        _fail("branch/head changed during admission")
    _tag()
    return result
